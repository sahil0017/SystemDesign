"""
Data models for the SystemDesign agent.
"""

import re
from dataclasses import dataclass, field
from datetime import datetime
from enum import Enum
from typing import Optional


class Category(Enum):
    HLD = "hld"
    LLD = "lld"
    DISTRIBUTED_SYSTEMS = "distributed-systems"
    TRADEOFFS = "tradeoffs"
    JAVA = "java"


@dataclass
class TrendingProblem:
    """A problem discovered from a web source."""

    name: str
    category: Category
    source: str
    url: str
    description: str = ""
    key_concepts: list = field(default_factory=list)
    source_count: int = 1
    last_seen: str = ""

    @property
    def slug(self) -> str:
        """Return a URL-safe slug for the problem name."""
        slug = self.name.lower().strip()
        slug = re.sub(r"[^a-z0-9]+", "-", slug)
        slug = slug.strip("-")
        return slug

    def to_dict(self) -> dict:
        """Serialize to dict for run history."""
        return {
            "name": self.name,
            "slug": self.slug,
            "category": self.category.value,
            "source": self.source,
        }


@dataclass
class ExistingProblem:
    """A problem already present in the repository."""

    name: str
    category: Category
    path: str
    slug: str


@dataclass
class GeneratedFile:
    """A file generated by the agent."""

    path: str
    content: str
    category: Category
    problem_name: str


@dataclass
class RunHistory:
    """Tracks problems added in previous runs to avoid duplicates."""

    added_slugs: set = field(default_factory=set)
    last_run: str = ""
    pr_urls: list = field(default_factory=list)

    def to_dict(self) -> dict:
        return {
            "added_slugs": list(self.added_slugs),
            "last_run": self.last_run,
            "pr_urls": self.pr_urls,
        }

    @classmethod
    def from_dict(cls, data: dict) -> "RunHistory":
        return cls(
            added_slugs=set(data.get("added_slugs", [])),
            last_run=data.get("last_run", ""),
            pr_urls=data.get("pr_urls", []),
        )
