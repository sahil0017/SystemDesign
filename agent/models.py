"""
Data models for the SystemDesign agent.
"""

from dataclasses import dataclass, field
from enum import Enum
from typing import Optional


class Category(Enum):
    HLD = "hld"
    LLD = "lld"
    DISTRIBUTED_SYSTEMS = "distributed-systems"
    TRADEOFFS = "tradeoffs"
    JAVA = "java"


@dataclass
class TrendingProblem:
    """A problem discovered from a web source."""

    name: str
    category: Category
    source: str
    url: str
    description: str = ""
    key_concepts: list = field(default_factory=list)

    @property
    def slug(self) -> str:
        """Return a URL-safe slug for the problem name."""
        import re

        slug = self.name.lower().strip()
        slug = re.sub(r"[^a-z0-9]+", "-", slug)
        slug = slug.strip("-")
        return slug


@dataclass
class ExistingProblem:
    """A problem already present in the repository."""

    name: str
    category: Category
    path: str
    slug: str


@dataclass
class GeneratedFile:
    """A file generated by the agent."""

    path: str
    content: str
    category: Category
    problem_name: str
